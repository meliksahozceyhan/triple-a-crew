// ---------- small utils ----------

function parseArgs(argv) {
  const positional = [];
  const flags = {};
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a.startsWith("--")) {
      const next = argv[i + 1];
      if (next === undefined || next.startsWith("--")) flags[a.slice(2)] = true;
      else {
        flags[a.slice(2)] = next;
        i++;
      }
    } else positional.push(a);
  }
  return { positional, flags };
}

function git(args, cwd = process.cwd()) {
  try {
    return execFileSync("git", args, {
      cwd,
      encoding: "utf8",
      stdio: ["ignore", "pipe", "ignore"],
      maxBuffer: 64 * 1024 * 1024,
    }).trimEnd();
  } catch {
    return null;
  }
}

const pad = (n) => String(n).padStart(2, "0");
function localStamp(d = new Date(), sep = " ") {
  return `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}${sep}${pad(d.getHours())}${sep === " " ? ":" : ""}${pad(d.getMinutes())}`;
}
function isoLocal(d = new Date()) {
  const off = -d.getTimezoneOffset();
  const abs = Math.abs(off);
  const date = `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}`;
  const time = `${pad(d.getHours())}:${pad(d.getMinutes())}:${pad(d.getSeconds())}`;
  return `${date}T${time}${off >= 0 ? "+" : "-"}${pad(Math.floor(abs / 60))}:${pad(abs % 60)}`;
}
function ago(ms) {
  const m = Math.round(ms / 60000);
  if (m < 60) return `${m}m`;
  const h = Math.round(m / 60);
  return h < 48 ? `${h}h` : `${Math.round(h / 24)}d`;
}

const slugify = (s, max = 60) =>
  String(s)
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, max)
    .replace(/-+$/, "");

function clip(s, n) {
  const flat = String(s).replace(/\s*\n\s*/g, " ⏎ ").trim();
  return flat.length > n ? `${flat.slice(0, n)}… (+${flat.length - n} chars)` : flat;
}

function code(s) {
  const t = String(s);
  return t.includes("`") ? `\`\` ${t} \`\`` : `\`${t}\``;
}

// Best-effort scrub of credentials that may appear in prompts or commands.
function redact(s) {
  return String(s)
    .replace(/(Bearer\s+)[A-Za-z0-9._~+/-]+=*/g, "$1<redacted>")
    .replace(
      /\b((?:api[_-]?key|access[_-]?token|refresh[_-]?token|token|secret|client[_-]?secret|password|passwd|authorization)["']?\s*[:=]\s*["']?)[^\s"'&,]+/gi,
      "$1<redacted>",
    )
    .replace(/\b(?:sk-[A-Za-z0-9_-]{16,}|gh[pousr]_[A-Za-z0-9]{20,}|xox[abprs]-[A-Za-z0-9-]{10,})/g, "<redacted>");
}

function safeReaddir(dir) {
  try {
    return fs.readdirSync(dir);
  } catch {
    return [];
  }
}

function readJsonl(file) {
  const out = [];
  for (const line of fs.readFileSync(file, "utf8").split("\n")) {
    if (!line) continue;
    try {
      out.push(JSON.parse(line));
    } catch {
      // partially written trailing line
    }
  }
  return out;
}

function resultText(content) {
  if (typeof content === "string") return content;
  if (Array.isArray(content))
    return content
      .filter((c) => c?.type === "text")
      .map((c) => c.text)
      .join("\n");
  return "";
}

// ---------- repo ----------

function resolveBase(flag) {
  const candidates = [];
  if (typeof flag === "string" && flag) candidates.push(flag);
  const originHead = git(["symbolic-ref", "--short", "refs/remotes/origin/HEAD"]);
  if (originHead) candidates.push(originHead);
  candidates.push("origin/main", "main", "origin/master", "master");
  for (const c of candidates) if (git(["rev-parse", "--verify", "--quiet", `${c}^{commit}`])) return c;
  return null;
}

function repoInfo(baseFlag) {
  const toplevel = git(["rev-parse", "--show-toplevel"]);
  if (!toplevel) return null;
  const commonDir = git(["rev-parse", "--path-format=absolute", "--git-common-dir"]);
  const mainWorktree = commonDir && path.basename(commonDir) === ".git" ? path.dirname(commonDir) : toplevel;
  const base = resolveBase(baseFlag);
  return {
    toplevel,
    mainWorktree,
    branch: git(["branch", "--show-current"]) || "(detached)",
    head: git(["rev-parse", "HEAD"]),
    base,
    mergeBase: base ? git(["merge-base", "HEAD", base]) : null,
  };
}

function statusMap(repo) {
  const map = new Map();
  const out = git(["status", "--porcelain=v1", "--untracked-files=all"], repo.toplevel) ?? "";
  for (const line of out.split("\n")) {
    if (!line) continue;
    const xy = line.slice(0, 2);
    let p = line.slice(3);
    if (p.includes(" -> ")) p = p.split(" -> ")[1];
    map.set(p.replace(/^"|"$/g, ""), xy.trim() || xy);
  }
  return map;
}

function handoffDir(repo, create) {
  // .crew/, not .claude/: Claude Code prompts for (or denies) every write under .claude/.
  // A repository rooted at the home directory (dotfiles kept in git) is not a project root.
  const main = repo?.mainWorktree;
  const root = main && path.resolve(main) !== path.resolve(os.homedir()) ? main : process.cwd();
  const dir = process.env.HANDOFF_DIR || path.join(root, ".crew", "handoffs");
  if (create) {
    fs.mkdirSync(dir, { recursive: true });
    const gi = path.join(dir, ".gitignore");
    if (!fs.existsSync(gi)) fs.writeFileSync(gi, "# Session handoffs are local working notes; never commit them.\n*\n");
  }
  return dir;
}

// ---------- transcript ----------

function claudeProjectsDir() {
  return path.join(process.env.CLAUDE_CONFIG_DIR || path.join(os.homedir(), ".claude"), "projects");
}
const projectSlug = (p) => p.replace(/[^a-zA-Z0-9]/g, "-");

function findTranscript(sessionFlag, repo) {
  const id =
    (typeof sessionFlag === "string" && sessionFlag.trim()) ||
    process.env.CLAUDE_SESSION_ID ||
    process.env.CLAUDE_CODE_SESSION_ID ||
    "";
  if (id.endsWith(".jsonl")) {
    return fs.existsSync(id)
      ? { file: path.resolve(id), how: "--session file" }
      : { file: null, how: `transcript ${id} not found` };
  }
  const projects = claudeProjectsDir();
  const dirs = [...new Set([process.cwd(), repo?.toplevel].filter(Boolean))].map((d) =>
    path.join(projects, projectSlug(d)),
  );
  if (id) {
    const candidates = [...dirs, ...safeReaddir(projects).map((d) => path.join(projects, d))];
    for (const d of candidates) {
      const f = path.join(d, `${id}.jsonl`);
      if (fs.existsSync(f)) return { file: f, how: "session id" };
    }
    return { file: null, how: `no transcript for session ${id}` };
  }
  let best = null;
  for (const d of dirs)
    for (const name of safeReaddir(d)) {
      if (!name.endsWith(".jsonl")) continue;
      const f = path.join(d, name);
      const m = fs.statSync(f).mtimeMs;
      if (!best || m > best.m) best = { f, m };
    }
  return best
    ? {
        file: best.f,
        how: "newest transcript for this directory — pass --session <id> if several sessions are active",
      }
    : { file: null, how: "no transcript found" };
}

// Calls cb(use, result) for every tool_use that has a matching tool_result.
function pairTools(recs, cb) {
  const uses = new Map();
  for (const r of recs) {
    if (r.type === "assistant") {
      for (const c of r.message?.content ?? [])
        if (c?.type === "tool_use") uses.set(c.id, { name: c.name, input: c.input ?? {}, ts: r.timestamp });
    } else if (r.type === "user" && Array.isArray(r.message?.content)) {
      for (const c of r.message.content) {
        if (c?.type !== "tool_result") continue;
        const use = uses.get(c.tool_use_id);
        if (!use) continue;
        const text = resultText(c.content);
        cb(use, { isError: !!c.is_error, text, tur: r.toolUseResult, ts: r.timestamp });
      }
    }
  }
}

function recordEdit(edits, use, via) {
  const p = use.input.file_path ?? use.input.notebook_path;
  if (!p) return;
  const e = edits.get(p) ?? { count: 0, tools: new Set(), via: new Set(), last: null };
  e.count++;
  e.tools.add(use.name);
  if (via) e.via.add(via);
  e.last = use.ts;
  edits.set(p, e);
}

function humanPrompt(r) {
  if (r.type !== "user" || r.isMeta || r.isCompactSummary || r.isVisibleInTranscriptOnly) return null;
  if (r.origin && r.origin.kind !== "human") return null;
  const content = r.message?.content;
  let text;
  let images = 0;
  if (typeof content === "string") text = content;
  else if (Array.isArray(content)) {
    if (content.some((c) => c?.type === "tool_result")) return null;
    text = content
      .filter((c) => c?.type === "text")
      .map((c) => c.text)
      .join("\n");
    images = content.filter((c) => c?.type === "image").length;
  } else return null;
  text = text.replace(/<system-reminder>[\s\S]*?<\/system-reminder>/g, "").trim();
  if (!text || /^\[Request interrupted/.test(text) || /^<local-command-(stdout|stderr|caveat)>/.test(text)) return null;
  const cmd = text.match(/<command-name>([^<]*)<\/command-name>/);
  if (cmd) {
    const args = text.match(/<command-args>([\s\S]*?)<\/command-args>/)?.[1]?.trim() ?? "";
    text = `${cmd[1].trim()}${args ? ` ${args}` : ""}`;
  }
  if (images) text += ` [+${images} image${images > 1 ? "s" : ""}]`;
  return { ts: r.timestamp, text };
}

function analyzeTranscript(file) {
  const recs = readJsonl(file);
  const s = {
    file,
    sessionId: path.basename(file, ".jsonl"),
    title: null,
    start: null,
    end: null,
    cwd: null,
    compactions: 0,
    prompts: [],
    edits: new Map(),
    reads: new Map(),
    bash: [],
    denials: [],
    questions: [],
    plans: [],
    agents: [],
    skills: [],
    tasks: new Map(),
    todos: null,
    handoffsRead: new Set(),
  };
  for (const r of recs) {
    if (r.timestamp) {
      s.start ??= r.timestamp;
      s.end = r.timestamp;
    }
    s.cwd ??= r.cwd ?? null;
    if (r.type === "custom-title" && r.customTitle) s.title = r.customTitle;
    if (r.type === "system" && r.subtype === "compact_boundary") s.compactions++;
    const p = humanPrompt(r);
    if (!p) continue;
    // A prompt re-sent after an interrupt repeats (or extends) the previous one.
    const norm = (t) => t.replace(/\s+/g, " ").trim();
    const prev = s.prompts.at(-1);
    if (prev && (norm(p.text).startsWith(norm(prev.text)) || norm(p.text).slice(0, 300) === norm(prev.text).slice(0, 300)))
      s.prompts.pop();
    s.prompts.push(p);
  }

  pairTools(recs, (use, res) => {
    const { name, input } = use;
    if (res.isError && DENIAL_RE.test(res.text)) s.denials.push({ tool: name, text: res.text });
    if (EDIT_TOOLS.has(name)) {
      if (!res.isError) recordEdit(s.edits, use);
    } else if (name === "Read" && input.file_path) {
      s.reads.set(input.file_path, (s.reads.get(input.file_path) ?? 0) + 1);
      if (HANDOFF_PATH_RE.test(input.file_path)) s.handoffsRead.add(input.file_path);
    } else if (name === "Bash" && input.command) {
      if (DENIAL_RE.test(res.text)) return;
      s.bash.push({
        cmd: input.command,
        desc: input.description ?? "",
        error: res.isError || /^Exit code \d+/.test(res.text),
        out: res.text,
      });
    } else if (name === "AskUserQuestion") {
      const answers = res.tur?.answers ?? {};
      for (const [q, a] of Object.entries(answers)) {
        const note = res.tur?.annotations?.[q]?.notes;
        s.questions.push({ q, a: note ? `${a} — note: ${note}` : a });
      }
    } else if (name === "ExitPlanMode" && !res.isError) {
      const title = String(input.plan ?? "").split("\n").find((l) => l.trim()) ?? "(untitled plan)";
      s.plans.push({ title: title.replace(/^#+\s*/, ""), file: res.tur?.filePath ?? null, ts: res.ts });
    } else if (name === "Agent" || name === "Task") {
      s.agents.push({
        desc: input.description ?? "",
        type: input.subagent_type ?? "general-purpose",
        bg: !!input.run_in_background,
        error: res.isError,
      });
    } else if (name === "Skill" && input.skill) {
      s.skills.push(input.skill);
    } else if (name === "TaskCreate" && !res.isError) {
      const id = res.tur?.task?.id ?? res.text.match(/Task #(\S+)/)?.[1];
      if (id) s.tasks.set(String(id), { subject: input.subject ?? "", status: "pending" });
    } else if (name === "TaskUpdate" && input.taskId != null) {
      const t = s.tasks.get(String(input.taskId));
      if (!t) return;
      if (input.status === "deleted") s.tasks.delete(String(input.taskId));
      else {
        if (input.status) t.status = input.status;
        if (input.subject) t.subject = input.subject;
      }
    } else if (name === "TodoWrite" && Array.isArray(input.todos)) {
      s.todos = input.todos;
    }
  });

  // Edits made by subagents live in <session>/subagents/agent-*.jsonl.
  const subDir = path.join(file.replace(/\.jsonl$/, ""), "subagents");
  for (const name of safeReaddir(subDir)) {
    if (!name.endsWith(".jsonl")) continue;
    let desc = name.replace(/\.jsonl$/, "");
    try {
      desc = JSON.parse(fs.readFileSync(path.join(subDir, name.replace(/\.jsonl$/, ".meta.json")), "utf8")).description ?? desc;
    } catch {
      // meta file is optional
    }
    pairTools(readJsonl(path.join(subDir, name)), (use, res) => {
      if (EDIT_TOOLS.has(use.name) && !res.isError) recordEdit(s.edits, use, `subagent "${desc}"`);
    });
  }
  return s;
}

// ---------- facts rendering ----------

function relToRepo(p, repo) {
  if (repo && p.startsWith(repo.toplevel + path.sep)) return p.slice(repo.toplevel.length + 1);
  return p.replace(os.homedir(), "~");
}

function renderGit(repo, out) {
  out.push("### Git");
  if (!repo) {
    out.push("- Not a git repository.");
    return;
  }
  const subject = git(["log", "-1", "--format=%s"]) ?? "";
  out.push(`- Worktree: ${code(repo.toplevel)}${repo.mainWorktree !== repo.toplevel ? ` (main checkout: ${code(repo.mainWorktree)})` : ""}`);
  out.push(`- Branch: ${code(repo.branch)} @ ${code(repo.head?.slice(0, 9) ?? "?")} "${subject}"`);
  const upstream = git(["rev-parse", "--abbrev-ref", "--symbolic-full-name", "@{u}"]);
  if (upstream) {
    const [behind, ahead] = (git(["rev-list", "--left-right", "--count", "@{u}...HEAD"]) ?? "0\t0").split(/\s+/);
    out.push(`- Upstream: ${code(upstream)} (ahead ${ahead}, behind ${behind})`);
  } else out.push("- Upstream: none (branch not pushed)");
  if (repo.base && repo.mergeBase) {
    out.push(`- Base: ${code(repo.base)} (merge-base ${code(repo.mergeBase.slice(0, 9))})`);
    const log = git(["log", "--format=%h %s", `${repo.mergeBase}..HEAD`]) ?? "";
    const commits = log ? log.split("\n") : [];
    out.push(`- Commits on branch since base: ${commits.length}`);
    for (const c of commits.slice(0, 25)) out.push(`  - ${c}`);
    if (commits.length > 25) out.push(`  - … ${commits.length - 25} more`);
  }
  const status = git(["status", "--short"], repo.toplevel) ?? "";
  const lines = status ? status.split("\n") : [];
  out.push(`- Working tree: ${lines.length ? `${lines.length} changed/untracked path(s)` : "clean"}`);
  if (lines.length) {
    out.push("  ```");
    for (const l of lines.slice(0, 50)) out.push(`  ${l}`);
    if (lines.length > 50) out.push(`  … ${lines.length - 50} more`);
    out.push("  ```");
  }
  if (repo.mergeBase) {
    const stat = git(["diff", "--stat=120", repo.mergeBase], repo.toplevel) ?? "";
    const statLines = stat ? stat.split("\n") : [];
    if (statLines.length) {
      out.push(`- Tracked diff vs merge-base (committed + uncommitted): ${statLines.at(-1).trim()}`);
      const files = statLines.slice(0, -1);
      out.push("  ```");
      for (const l of files.slice(0, 40)) out.push(`  ${l.trim()}`);
      if (files.length > 40) out.push(`  … ${files.length - 40} more`);
      out.push("  ```");
    }
  }
  const stashes = git(["stash", "list"]) ?? "";
  if (stashes) out.push(`- Stashes: ${stashes.split("\n").length}`);
}

function renderSession(s, how, repo, clipAt, out) {
  out.push("### Session");
  if (!s) {
    out.push(`- Transcript: not available (${how}).`);
    return;
  }
  const span = s.start && s.end ? `${localStamp(new Date(s.start))} → ${localStamp(new Date(s.end))}` : "?";
  out.push(`- Title: ${s.title ? `"${s.title}"` : "(none)"} · id ${code(s.sessionId)}`);
  out.push(`- Transcript: ${code(s.file.replace(os.homedir(), "~"))} (picked by ${how})`);
  out.push(`- Span: ${span} · ${s.prompts.length} user prompt(s) · ${s.compactions} compaction(s)`);
  if (s.handoffsRead.size)
    out.push(`- Previous handoff(s) read this session: ${[...s.handoffsRead].map((p) => code(relToRepo(p, repo))).join(", ")}`);

  out.push("", "### User prompts (chronological)");
  if (!s.prompts.length) out.push("- (none)");
  s.prompts.forEach((p, i) => {
    const t = p.ts ? localStamp(new Date(p.ts)).slice(11) : "";
    out.push(`${i + 1}. [${t}] ${redact(clip(p.text, clipAt))}`);
  });

  if (s.questions.length) {
    out.push("", "### User answers to agent questions");
    for (const q of s.questions) out.push(`- ${clip(q.q, 200)} → **${clip(q.a, 200)}**`);
  }
  const planFiles = [...s.edits.keys()].filter(
    (p) => p.includes(`${path.sep}.claude${path.sep}plans${path.sep}`) && !s.plans.some((pl) => pl.file === p),
  );
  if (s.plans.length || planFiles.length) {
    out.push("", "### Plans");
    for (const p of s.plans) out.push(`- approved: ${p.title}${p.file ? ` — ${code(p.file.replace(os.homedir(), "~"))}` : ""}`);
    for (const p of planFiles) out.push(`- plan file written (approval not recorded): ${code(p.replace(os.homedir(), "~"))}`);
  }

  out.push("", "### Files edited this session (Edit/Write tools, incl. subagents)");
  const status = repo ? statusMap(repo) : new Map();
  const onBranch = new Set(
    repo?.mergeBase ? (git(["diff", "--name-only", `${repo.mergeBase}..HEAD`], repo.toplevel) ?? "").split("\n") : [],
  );
  const edits = [...s.edits.entries()].sort((a, b) => String(a[1].last).localeCompare(String(b[1].last)));
  if (!edits.length) out.push("- (none via tools — check the git section for changes made by shell commands)");
  for (const [p, e] of edits) {
    const rel = relToRepo(p, repo);
    let gitState = "outside repo";
    if (repo && p.startsWith(repo.toplevel + path.sep)) {
      const st = status.get(rel);
      if (st === "??") gitState = "untracked";
      else if (st) gitState = `uncommitted (${st})`;
      else if (onBranch.has(rel)) gitState = "committed on branch";
      else if (!fs.existsSync(p)) gitState = "deleted";
      else gitState = "clean (no uncommitted or branch diff)";
    }
    const via = e.via.size ? ` · via ${[...e.via].join(", ")}` : "";
    out.push(`- ${code(rel)} — ${e.count}× ${[...e.tools].join("/")} · ${gitState}${via}`);
  }

  const reads = [...s.reads.entries()].filter(([p]) => !s.edits.has(p)).sort((a, b) => b[1] - a[1]);
  if (reads.length) {
    out.push("", "### Files read but not edited (most-read first)");
    for (const [p, n] of reads.slice(0, 20)) out.push(`- ${code(relToRepo(p, repo))}${n > 1 ? ` (${n}×)` : ""}`);
    if (reads.length > 20) out.push(`- … ${reads.length - 20} more`);
  }

  const tasks = [...s.tasks.values()];
  const todos = s.todos?.map((t) => ({ subject: t.content, status: t.status })) ?? [];
  if (tasks.length || todos.length) {
    out.push("", "### Task list (final state)");
    const mark = { completed: "[x]", in_progress: "[~]", pending: "[ ]" };
    for (const t of [...tasks, ...todos]) out.push(`- ${mark[t.status] ?? `[${t.status}]`} ${t.subject}`);
  }

  if (s.agents.length) {
    out.push("", "### Subagents launched");
    for (const a of s.agents) out.push(`- ${a.desc} (${a.type})${a.bg ? " [background]" : ""}${a.error ? " [errored]" : ""}`);
  }
  if (s.skills.length) out.push("", `### Skills invoked`, `- ${[...new Set(s.skills)].join(", ")}`);

  const failed = s.bash.filter((b) => b.error);
  if (failed.length) {
    out.push("", `### Commands that failed (${failed.length} of ${s.bash.length}) — lesson candidates`);
    for (const b of failed.slice(-20)) {
      const lines = b.out
        .split("\n")
        .map((l) => l.trim())
        .filter((l) => l && !/^Exit code \d+$/.test(l) && !/^Shell cwd was reset/.test(l));
      const errLine =
        lines.find((l) => /error|fail|not found|no such|denied|cannot|can't|unmatched|exception|invalid|✘/i.test(l)) ??
        lines.at(-1) ??
        "";
      out.push(`- ${code(redact(clip(b.cmd, 160)))}${b.desc ? ` (${b.desc})` : ""} → ${redact(clip(errLine, 200))}`);
    }
  }
  if (s.denials.length) {
    out.push("", "### Tool calls the user denied or rejected — respect these");
    for (const d of s.denials) out.push(`- ${d.tool}: ${redact(clip(d.text, 220))}`);
  }
  const seen = new Set();
  const recent = [];
  for (const b of [...s.bash].reverse()) {
    if (seen.has(b.cmd)) continue;
    seen.add(b.cmd);
    recent.push(b);
    if (recent.length === 25) break;
  }
  if (recent.length) {
    out.push("", `### Recent commands (last ${recent.length} unique, newest last)`);
    for (const b of recent.reverse())
      out.push(`- ${b.error ? "✗ " : ""}${b.desc ? `${b.desc}: ` : ""}${code(redact(clip(b.cmd, 160)))}`);
  }
}

function buildFacts({ session, base, clipAt = 500 }) {
  const repo = repoInfo(base);
  const found = findTranscript(session, repo);
  let s = null;
  if (found.file) {
    try {
      s = analyzeTranscript(found.file);
    } catch (err) {
      // A sandboxed shell (Claude Code's Bash sandbox, eval runs) cannot read the config dir: keep the git facts.
      if (err.code !== "EPERM" && err.code !== "EACCES") throw err;
      found.how = `transcript unreadable (${err.code}), probably a sandboxed shell; these facts cover git only`;
    }
  }
  const out = ["## Session facts (auto-generated)", `_Generated ${localStamp()} by handoff.mjs from git and the session transcript. Hard data only — the narrative above carries intent._`, ""];
  renderSession(s, found.how, repo, Number(clipAt) || 500, out);
  out.push("");
  renderGit(repo, out);
  return { repo, session: s, markdown: out.join("\n") };
}

// ---------- handoff files ----------

function splitFrontmatter(text) {
  const m = text.match(/^---\n([\s\S]*?)\n---\n?/);
  if (!m) return { fm: {}, body: text };
  const fm = {};
  for (const line of m[1].split("\n")) {
    const kv = line.match(/^([\w-]+):\s*(.*)$/);
    if (!kv) continue;
    let v = kv[2].trim();
    if (v.startsWith('"')) {
      try {
        v = JSON.parse(v);
      } catch {
        // keep raw
      }
    }
    fm[kv[1]] = v;
  }
  return { fm, body: text.slice(m[0].length) };
}

function joinFrontmatter(fm, body) {
  const lines = Object.entries(fm)
    .filter(([, v]) => v !== undefined && v !== null && v !== "")
    .map(([k, v]) => `${k}: ${typeof v === "number" ? v : JSON.stringify(String(v))}`);
  return `---\n${lines.join("\n")}\n---\n\n${body.replace(/^\n+/, "")}`;
}

function stripFacts(body) {
  return body.replace(/\n*<!-- handoff:facts:start[\s\S]*?<!-- handoff:facts:end -->\n*/g, "\n").trimEnd();
}

// Level-2 sections of the narrative, keyed by normalized heading ("## 4. Decisions" → "decisions").
function sections(body) {
  const parts = body.split(/^(?=## )/m);
  return parts.map((text) => {
    const h = text.match(/^##\s+(?:\d+[.)]\s*)?(.+)$/m);
    return { key: h && text.startsWith("## ") ? h[1].trim().toLowerCase() : null, text: text.trimEnd() };
  });
}

function workItems(sectionText) {
  return sectionText
    .split(/^(?=### )/m)
    .filter((t) => /^###\s+W\d+/.test(t))
    .map((t) => ({ id: t.match(/^###\s+(W\d+)/)[1], title: t.split("\n")[0].replace(/^###\s+/, ""), text: t.trimEnd() }));
}

function validate(body, repo) {
  const warnings = [];
  const secs = sections(body);
  for (const name of REQUIRED_SECTIONS)
    if (!secs.some((s) => s.key?.startsWith(name.toLowerCase()))) warnings.push(`missing section "## ${name}"`);
  const placeholders = body.match(/\{\{[^}]*\}\}/g);
  if (placeholders) warnings.push(`unfilled template placeholders: ${[...new Set(placeholders)].slice(0, 5).join(", ")}`);
  const open = secs.find((s) => s.key?.startsWith("open work"));
  if (open) {
    const items = workItems(open.text);
    const bodyText = open.text.replace(/^##.*\n/, "").trim();
    if (!items.length && !/^(none|nothing|n\/a)\b/i.test(bodyText.replace(/^[-*_\s]+/, "")))
      warnings.push('"Open work" has no "### W1 — …" items; subagent briefs need them (or write "None.")');
  }
  if (repo) {
    const missing = new Set();
    const refs = [...body.matchAll(/`([^`\s]+\/[^`\s]+\.[A-Za-z0-9]+)(?::\d+(?:-\d+)?)?`/g), ...body.matchAll(/\]\(([^)\s#]+)(?:#[^)]*)?\)/g)];
    for (const [, ref] of refs) {
      if (/^[a-z]+:\/\//i.test(ref) || ref.includes("*") || ref.includes("<") || ref.startsWith("~")) continue;
      const clean = ref.replace(/:\d+(?:-\d+)?$/, "");
      const abs = path.isAbsolute(clean) ? clean : path.join(repo.toplevel, clean);
      if (!fs.existsSync(abs)) missing.add(clean);
    }
    if (missing.size)
      warnings.push(`referenced paths not found (fine if deleted/renamed on purpose): ${[...missing].slice(0, 12).join(", ")}`);
  }
  return warnings;
}

function listHandoffs(repo) {
  const dir = handoffDir(repo, false);
  return safeReaddir(dir)
    .filter((n) => n.endsWith(".md"))
    .map((n) => {
      const file = path.join(dir, n);
      const { fm } = splitFrontmatter(fs.readFileSync(file, "utf8"));
      const created = Date.parse(fm.updated || fm.created || "") || fs.statSync(file).mtimeMs;
      return { file, fm, created };
    })
    .sort((a, b) => b.created - a.created);
}

function latestHandoff(repo, any) {
  const all = listHandoffs(repo);
  if (!all.length) return null;
  if (any || !repo) return all[0];
  return all.find((h) => h.fm.branch === repo.branch) ?? null;
}

// ---------- commands ----------

function cmdPath(flags) {
  const repo = repoInfo();
  const dir = handoffDir(repo, true);
  const label = typeof flags.topic === "string" && flags.topic ? flags.topic : repo?.branch ?? "session";
  const stem = `${localStamp(new Date(), "-")}-${slugify(label) || "session"}`;
  let file = path.join(dir, `${stem}.md`);
  for (let i = 2; fs.existsSync(file); i++) file = path.join(dir, `${stem}-${i}.md`);
  console.log(file);
}

function cmdFinalize(positional, flags) {
  const file = positional[0];
  if (!file || !fs.existsSync(file)) fail(`finalize: file not found: ${file ?? "(none)"}`);
  const { fm: oldFm, body } = splitFrontmatter(fs.readFileSync(file, "utf8"));
  const narrative = stripFacts(body);
  const { repo, session, markdown } = buildFacts({ session: flags.session, base: flags.base });
  const previous = session ? [...session.handoffsRead].filter((p) => path.resolve(p) !== path.resolve(file)) : [];
  const title = narrative.match(/^#\s+(.+)$/m)?.[1]?.replace(/^Handoff:\s*/i, "") ?? oldFm.title;
  const fm = {
    handoff: 1,
    title,
    created: oldFm.created || isoLocal(),
    updated: isoLocal(),
    session: session?.sessionId ?? oldFm.session,
    session_title: session?.title ?? oldFm.session_title,
    worktree: repo?.toplevel,
    branch: repo?.branch,
    head: repo?.head,
    base: repo?.base,
    merge_base: repo?.mergeBase,
    previous: previous.length ? previous.map((p) => path.basename(p)).join(", ") : oldFm.previous,
  };
  const content = `${joinFrontmatter(fm, narrative)}\n\n${FACTS_START}\n\n${markdown}\n\n${FACTS_END}\n`;
  fs.writeFileSync(file, content);
  const warnings = validate(narrative, repo);
  const narrativeWords = narrative.split(/\s+/).filter(Boolean).length;
  console.log(`Finalized ${file}`);
  console.log(`  narrative: ~${narrativeWords} words · total: ${content.length} chars (~${Math.round(content.length / 4)} tokens)`);
  if (warnings.length) {
    console.log(`  ${warnings.length} warning(s) — fix and re-run finalize:`);
    for (const w of warnings) console.log(`  - ${w}`);
  } else console.log("  checks passed: all sections present, no placeholders, referenced paths exist");
}

function cmdResume(positional, flags) {
  const repo = repoInfo();
  let h;
  if (positional[0]) {
    if (!fs.existsSync(positional[0])) fail(`resume: file not found: ${positional[0]}`);
    h = { file: path.resolve(positional[0]), fm: splitFrontmatter(fs.readFileSync(positional[0], "utf8")).fm };
  } else {
    h = latestHandoff(repo, flags.any);
    if (!h) {
      const any = latestHandoff(repo, true);
      if (!any) fail(`resume: no handoffs in ${handoffDir(repo, false)}`);
      console.log(`No handoff recorded for branch ${repo?.branch}; newest overall is for branch ${any.fm.branch}.`);
      h = any;
    }
  }
  const { fm } = h;
  const created = Date.parse(fm.updated || fm.created || "");
  console.log(`Handoff: ${h.file}`);
  console.log(`Title:   ${fm.title ?? "(untitled)"}`);
  console.log(`Written: ${fm.updated || fm.created || "?"}${created ? ` (${ago(Date.now() - created)} ago)` : ""} by session ${fm.session ?? "?"}${fm.session_title ? ` "${fm.session_title}"` : ""}`);
  if (fm.previous) console.log(`Chain:   continues ${fm.previous}`);
  if (!repo) return;
  console.log("\nDrift since the handoff:");
  if (fm.worktree && fm.worktree !== repo.toplevel) console.log(`- ⚠ written in worktree ${fm.worktree}; you are in ${repo.toplevel}`);
  if (fm.branch && fm.branch !== repo.branch) console.log(`- ⚠ written on branch ${fm.branch}; you are on ${repo.branch} (git switch ${fm.branch} unless intentional)`);
  else console.log(`- branch: ${repo.branch} (same)`);
  if (fm.head) {
    if (fm.head === repo.head) console.log(`- HEAD: unchanged (${fm.head.slice(0, 9)})`);
    else if (git(["cat-file", "-e", `${fm.head}^{commit}`]) === null) console.log(`- ⚠ recorded HEAD ${fm.head.slice(0, 9)} no longer exists here`);
    else if (git(["merge-base", "--is-ancestor", fm.head, "HEAD"]) !== null) {
      const log = git(["log", "--format=%h %s", `${fm.head}..HEAD`]) ?? "";
      const commits = log ? log.split("\n") : [];
      console.log(`- HEAD: ${commits.length} new commit(s) since handoff`);
      for (const c of commits.slice(0, 15)) console.log(`    ${c}`);
    } else console.log(`- ⚠ HEAD ${repo.head.slice(0, 9)} is not a descendant of recorded ${fm.head.slice(0, 9)} (rebase/reset?)`);
  }
  const status = git(["status", "--short"], repo.toplevel) ?? "";
  const lines = status ? status.split("\n") : [];
  console.log(`- working tree now: ${lines.length ? `${lines.length} changed/untracked path(s)` : "clean"}`);
  for (const l of lines.slice(0, 20)) console.log(`    ${l}`);
  console.log("\nNext: Read the handoff file in full, then act on its \"Next steps\" section.");
}

function cmdBrief(positional) {
  const [file, ...ids] = positional;
  if (!file || !fs.existsSync(file)) fail(`brief: file not found: ${file ?? "(none)"}`);
  const { fm, body } = splitFrontmatter(fs.readFileSync(file, "utf8"));
  const secs = sections(stripFacts(body));
  const items = workItems(secs.find((s) => s.key?.startsWith("open work"))?.text ?? "");
  const wanted = ids.map((i) => i.toUpperCase());
  const mine = items.filter((w) => wanted.includes(w.id));
  if (!wanted.length || mine.length !== wanted.length)
    fail(`brief: pass work item ids that exist in "Open work". Available: ${items.map((w) => w.id).join(", ") || "(none)"}`);
  const others = items.filter((w) => !wanted.includes(w.id));
  const out = [
    `# Subagent brief: ${mine.map((w) => w.title).join("; ")}`,
    "",
    `You are picking up part of a larger piece of work that another agent session started. Everything you need is below; the full handoff is at ${code(path.resolve(file))} if something here is unclear.`,
    "",
    `- Worktree: ${code(fm.worktree ?? "?")} · branch ${code(fm.branch ?? "?")} · base ${code(fm.base ?? "?")}`,
    `- Your assignment: ${mine.map((w) => w.id).join(", ")} only.`,
    others.length
      ? `- Other work items (owned by other agents — do not edit files that belong to them): ${others.map((w) => w.title).join("; ")}`
      : "- There are no other open work items.",
    "- When done, report back: files changed, how you verified (exact commands + results), anything left undone, and new lessons learned.",
    "",
  ];
  for (const sec of secs)
    if (BRIEF_SECTIONS.some((name) => sec.key?.startsWith(name.toLowerCase()))) out.push(sec.text, "");
  out.push("## Your work item(s)", "", ...mine.map((w) => `${w.text}\n`));
  console.log(out.join("\n").trimEnd());
}

function fail(msg) {
  console.error(msg);
  process.exit(1);
}

const [command, ...rest] = process.argv.slice(2);
const { positional, flags } = parseArgs(rest);
switch (command) {
  case "facts":
    console.log(buildFacts({ session: flags.session, base: flags.base, clipAt: flags.clip }).markdown);
    break;
  case "path":
    cmdPath(flags);
    break;
  case "finalize":
    cmdFinalize(positional, flags);
    break;
  case "resume":
    cmdResume(positional, flags);
    break;
  case "brief":
    cmdBrief(positional);
    break;
  case "latest": {
    const h = latestHandoff(repoInfo(), flags.any);
    if (!h) fail("no handoff found (try --any)");
    console.log(h.file);
    break;
  }
  case "list": {
    const all = listHandoffs(repoInfo());
    if (!all.length) console.log("(no handoffs)");
    for (const h of all) console.log(`${localStamp(new Date(h.created))}  ${h.fm.branch ?? "?"}  ${h.fm.title ?? ""}\n    ${h.file}`);
    break;
  }
  default:
    console.log(USAGE);
    if (command && command !== "help") process.exit(1);
}
