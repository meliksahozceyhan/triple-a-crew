#!/usr/bin/env node
// Helper for the Triple-A-Crew handoff skill.
//
// Gathers hard facts about the current agent session (git state + the Claude
// Code transcript) and manages handoff files under <main worktree>/.crew/handoffs/.
// The narrative (intent, decisions, lessons) is written by the agent; this
// script supplies the parts an agent tends to forget or lose to compaction.
//
// Run `node handoff.mjs help` for commands.

import { execFileSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";

